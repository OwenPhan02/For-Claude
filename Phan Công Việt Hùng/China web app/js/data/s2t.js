const WORD_KEYS = Object.keys(WORDS).sort((a, b) => b.length - a.length);

const cache = new Map();
export function toTrad(s) {
  if (!s) return s;
  if (cache.has(s)) return cache.get(s);
  let out = '', i = 0;
  outer: while (i < s.length) {
    for (const w of WORD_KEYS) {
      if (w.length > 1 && s.startsWith(w, i)) { out += WORDS[w]; i += w.length; continue outer; }
    }
    const c = s[i];
    out += MAP.get(c) || c;
    i++;
  }
  cache.set(s, out);
  return out;
}
